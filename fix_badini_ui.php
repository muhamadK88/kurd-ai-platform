$files = glob($root . '/*.blade.php');
$files = array_merge($files, glob($root . '/*/*.blade.php'));

$totalHits = 0;
$changedFiles = 0;

foreach ($files as $file) {
    $src = file_get_contents($file);
    $hits = 0;

    // Only ever rewrite the inside of data-ba="..."
    $out = preg_replace_callback(
        '/data-ba="([^"]*)"/u',
        function ($m) use ($fix, &$hits) {
            $val = html_entity_decode($m[1], ENT_QUOTES, 'UTF-8');
            foreach ($fix as $old => $new) {
                if ($val === $old || $m[1] === $old) {
                    $hits++;
                    return 'data-ba="' . $new . '"';
                }
            }
            return $m[0];
        },
        $src
    );

    if ($hits > 0 && $out !== $src) {
        $totalHits += $hits;
        $changedFiles++;
        printf("%-45s %d fix(es)\n", basename($file), $hits);
        if (!$dry) {
            file_put_contents($file, $out);
        }
    }
}

echo str_repeat('-', 60), "\n";
printf("%s: %d fixes across %d files\n", $dry ? 'DRY RUN' : 'APPLIED', $totalHits, $changedFiles);
